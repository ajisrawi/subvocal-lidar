"""Writes sdk_files.cmake: the SDK sources and include folders of Nordic's ble_app_hids_keyboard example (pca10040/s132
Makefile), minus the dev-kit parts (buttons/LEDs board support, UART, RTT logging, sensor simulator).
    python firmware/bluetooth/gen_sdk_files.py [path-to-nRF5_SDK_17.1.0]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SDK = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser('~'), 'nordic', 'nRF5_SDK_17.1.0_ddde560')
mk = open(os.path.join(SDK, 'examples', 'ble_peripheral', 'ble_app_hids_keyboard', 'pca10040', 's132', 'armgcc', 'Makefile'), encoding='utf-8').read()
BS = chr(92)

def block(name):
    m = re.search(name + r' \+= ' + re.escape(BS) + r'\n(.*?)\n\n', mk, re.S)
    return [l.strip().rstrip(BS).strip() for l in m.group(1).split('\n') if l.strip()]

dirs = [d.replace('$(SDK_ROOT)', '${NRF5_SDK}') for d in block('INC_FOLDERS') if d != '../config']
drop = ('bsp.c', 'bsp_btn_ble.c', 'boards.c', 'sensorsim.c', 'nrf_drv_uart.c', 'nrfx_uart.c', 'nrfx_uarte.c', 'main.c',
        'SEGGER_RTT', 'app_button.c', 'nrfx_gpiote.c', 'nrf_log_backend_uart.c', 'nrf_log_backend_rtt.c', 'nrf_log_backend_serial.c')
files = [f.replace('$(SDK_ROOT)', '${NRF5_SDK}') for f in block('SRC_FILES') if not any(d in f for d in drop)]
with open(os.path.join(HERE, 'sdk_files.cmake'), 'w', newline='\n') as f:
    f.write('# Generated by gen_sdk_files.py from the nRF5 SDK 17.1 ble_app_hids_keyboard Makefile (pca10040/s132).\n')
    f.write('set(SDK_SOURCES\n' + '\n'.join('  ' + x for x in files) + ')\n')
    f.write('set(SDK_INCLUDES\n' + '\n'.join('  ' + x for x in dirs) + ')\n')
print(len(files), 'sources,', len(dirs), 'include folders')
